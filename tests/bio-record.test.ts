import test from "node:test";
import assert from "node:assert/strict";

// eslint-disable-next-line @typescript-eslint/no-require-imports
const { syncBioRecord } = require("../scripts/bio-record.js");

test("числовой рекорд после слова «рекорд» обновляется", () => {
  assert.equal(
    syncBioRecord("Он известен стилем джиу-джитсу и рекордом 38-19-0, включая 21 победу сабмишеном.", "39-19-0"),
    "Он известен стилем джиу-джитсу и рекордом 39-19-0, включая 21 победу сабмишеном."
  );
});

test("рекорд словами переписывается с правильными окончаниями", () => {
  assert.equal(
    syncBioRecord("Его профессиональный рекорд составляет 20 побед, 7 поражений и 1 ничья, а тренируется он в ATT.", "21-7-1"),
    "Его профессиональный рекорд составляет 21 победа, 7 поражений и 1 ничья, а тренируется он в ATT."
  );
  assert.equal(
    syncBioRecord("Его профессиональный рекорд составляет 9 побед и 1 поражение.", "11-2-0"),
    "Его профессиональный рекорд составляет 11 побед и 2 поражения."
  );
  assert.equal(
    syncBioRecord("Его профессиональный рекорд составляет 19 побед и 6 поражений причём 13 из побед одержаны нокаутом.", "20-6-0"),
    "Его профессиональный рекорд составляет 20 побед и 6 поражений причём 13 из побед одержаны нокаутом."
  );
});

test("рекорд в организации и числа методов побед не трогаем", () => {
  const ufcOnly = "Он представляет Германию и имеет рекорд 0-1-0 в организации.";
  assert.equal(syncBioRecord(ufcOnly, "10-2-0"), ufcOnly);
  const inUfc = "В UFC его рекорд 5-2-0, а всего он провёл 20 боёв.";
  assert.equal(syncBioRecord(inUfc, "15-5-0"), inUfc);
  const methods = "Стиль включает 7 побед нокаутом и 3 сабмишеном.";
  assert.equal(syncBioRecord(methods, "22-6-0"), methods);
});

test("ничьи появляются, только если они были во фразе или в рекорде", () => {
  assert.equal(
    syncBioRecord("Его рекорд — 10 побед и 3 поражения.", "10-3-1"),
    "Его рекорд — 10 побед, 3 поражения и 1 ничья."
  );
});

test("английская биография обновляется так же", () => {
  assert.equal(
    syncBioRecord("He holds a professional record of 19-6-0 with 13 knockouts.", "20-6-0", "en"),
    "He holds a professional record of 20-6-0 with 13 knockouts."
  );
  assert.equal(
    syncBioRecord("His record stands at 9 wins and 1 loss.", "11-2-0", "en"),
    "His record stands at 11 wins and 2 losses."
  );
});

test("пустой или нечисловой рекорд ничего не меняет", () => {
  const bio = "Его рекорд составляет 9 побед и 1 поражение.";
  assert.equal(syncBioRecord(bio, ""), bio);
  assert.equal(syncBioRecord("", "10-1-0"), "");
  assert.equal(syncBioRecord(bio, "0-0-0(В-П-Н)"), bio);
});

test("форма «побед при поражениях» и множественные ничьи", () => {
  assert.equal(
    syncBioRecord("Его рекорд составляет 13 побед при 3 поражениях.", "14-3-0"),
    "Его рекорд составляет 14 побед при 3 поражениях."
  );
  assert.equal(
    syncBioRecord("Его рекорд составляет 8 побед при 1 поражении.", "9-2-0"),
    "Его рекорд составляет 9 побед при 2 поражениях."
  );
  assert.equal(
    syncBioRecord("С профессиональным рекордом 25 побед, 13 поражений и 5 ничьих.", "25-13-5"),
    "С профессиональным рекордом 25 побед, 13 поражений и 5 ничьих."
  );
});

test("ничья в любом падеже и словом не дублируется", () => {
  assert.equal(
    syncBioRecord("Завершил карьеру с рекордом 14 побед, 5 поражений и 1 ничьей.", "14-5-1"),
    "Завершил карьеру с рекордом 14 побед, 5 поражений и 1 ничья."
  );
  assert.equal(
    syncBioRecord("Его рекорд составляет 27 побед, 14 поражений и одна ничья.", "27-14-1"),
    "Его рекорд составляет 27 побед, 14 поражений и 1 ничья."
  );
});

test("винительный «ничью» распознаётся, творительный падеж не трогаем", () => {
  assert.equal(
    syncBioRecord("Имеет профессиональный рекорд 17 побед, 5 поражений и 1 ничью.", "18-5-1"),
    "Имеет профессиональный рекорд 18 побед, 5 поражений и 1 ничья."
  );
  const instrumental = "Завершил карьеру с рекордом 7 побед, 1 поражением и 1 ничьей.";
  assert.equal(syncBioRecord(instrumental, "7-1-1"), instrumental);
});

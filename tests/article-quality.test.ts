import assert from "node:assert/strict";
import test from "node:test";

import { cleanNewsText, cleanNewsTitle } from "../lib/article-quality";

test("префикс «Источник:» срезается, а заголовок остаётся", () => {
  assert.equal(
    cleanNewsTitle("Источник: Валентина Шевченко проведёт 14-й титульный бой в карьере на UFC 332"),
    "Валентина Шевченко проведёт 14-й титульный бой в карьере на UFC 332"
  );
});

test("префикс «Фото:» срезается, а заголовок остаётся", () => {
  assert.equal(
    cleanNewsTitle("Фото: Деметриус Джонсон и Алекс Перейра стали членами Зала славы UFC"),
    "Деметриус Джонсон и Алекс Перейра стали членами Зала славы UFC"
  );
});

test("слово «чемпионат» в обычном значении не выбрасывает заголовок", () => {
  const title = "Хабиб вспомнил, как в 15 лет встретил Фёдора Емельяненко на чемпионате Дагестана";

  assert.equal(cleanNewsTitle(title), title);
});

test("обычный заголовок не меняется", () => {
  const title = "Дана Уайт подтвердил инцидент с Намо Фазилем";

  assert.equal(cleanNewsTitle(title), title);
});

// Страховка на будущее: любой новый паттерн чистки, обнуливший заголовок, оставил бы
// статью с пустыми <title>, <h1> и headline — так уже случилось на проде.
test("заголовок никогда не становится пустым", () => {
  for (const title of ["Источник:", "Фото:", "«Чемпионат»", "источник: mmajunkie"]) {
    assert.notEqual(cleanNewsTitle(title), "", `обнулился заголовок ${JSON.stringify(title)}`);
  }
});

test("предложение с обычным словом «чемпионат» остаётся в тексте", () => {
  const body = [
    "Хабиб рассказал о начале пути.",
    "Он встретил Фёдора Емельяненко на чемпионате Дагестана в 2003 году."
  ].join("\n\n");

  assert.equal(cleanNewsText(body), body);
});

test("подпись об источнике из текста по-прежнему вырезается", () => {
  const body = ["Хабиб рассказал о начале пути.", "Источник: MMAJunkie"].join("\n\n");

  assert.equal(cleanNewsText(body), "Хабиб рассказал о начале пути.");
});

test("упоминание издания «Чемпионат» в кавычках из текста вырезается", () => {
  const body = ["Хабиб рассказал о начале пути.", "Об этом сообщает «Чемпионат»."].join("\n\n");

  assert.equal(cleanNewsText(body), "Хабиб рассказал о начале пути.");
});
